type LogoVariant = "full" | "word" | "mark";

const VIEWBOX: Record<LogoVariant, string> = {
  full: "0 0 336 100",
  word: "0 0 330 100",
  mark: "8 6 96 96",
};

export function Logo({
  variant = "word",
  className,
  ...rest
}: { variant?: LogoVariant } & SVGProps<SVGSVGElement>) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={VIEWBOX[variant]}
      role="img"
      aria-label="Aturseva"
      className={className}
      {...rest}
    >
      {variant === "mark" ? (
        SYMBOL
      ) : (
        <>
          {SYMBOL}
          {WORDMARK}
          {variant === "full" && TAGLINE}
        </>
      )}
    </svg>
  );
}
